// Writes public/modulo-sdk/*.js: ES modules that re-export the core's own
// React, ReactDOM, JSX runtime and Inertia from window.Modulo.vendor.
//
// A plugin bundle is an ES module with these imports left external. The page's
// import map points the bare specifiers at these shims, so a plugin shares the
// core's single React instead of loading a second one (which breaks hooks).
//
// The export lists are read from the installed packages, so they follow
// upgrades: run `npm run build:shims` after updating React or Inertia (the
// plugin-sdk test fails if they drift).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(root, 'public/modulo-sdk');

export const SHIMS = {
    'react.js': { specifier: 'react', vendor: 'react' },
    'react-dom.js': { specifier: 'react-dom', vendor: 'reactDOM' },
    'react-jsx-runtime.js': { specifier: 'react/jsx-runtime', vendor: 'jsxRuntime' },
    'inertia-react.js': { specifier: '@inertiajs/react', vendor: 'inertia' },
};

const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

/**
 * The admin kit plugins import as @modulo/ui: the names resources/js/plugin-ui.ts
 * re-exports (it is TypeScript with path aliases, so read, not imported).
 */
export function uiExports(source = readFileSync(resolve(root, 'resources/js/plugin-ui.ts'), 'utf8')) {
    const names = [];
    for (const [, list] of source.matchAll(/export\s*\{([^}]*)\}\s*from/g)) {
        for (const entry of list.split(',')) {
            const name = entry.trim().split(/\s+as\s+/).pop();
            if (name && identifier.test(name)) names.push(name);
        }
    }
    return names.sort();
}

export async function exportsOf(specifier) {
    const mod = await import(specifier);
    return Object.keys(mod)
        .filter((key) => key !== 'default' && identifier.test(key))
        .sort();
}

export function shimSource(vendor, names) {
    return [
        '// Generated by scripts/build-plugin-shims.mjs. Do not edit.',
        `const m = window.Modulo.vendor.${vendor};`,
        'export default m;',
        ...names.map((name) => `export const ${name} = m.${name};`),
        '',
    ].join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    mkdirSync(out, { recursive: true });
    for (const [file, { specifier, vendor }] of Object.entries(SHIMS)) {
        const names = await exportsOf(specifier);
        writeFileSync(resolve(out, file), shimSource(vendor, names));
        console.log(`${file}: ${names.length} exports from ${specifier}`);
    }
    const ui = uiExports();
    writeFileSync(resolve(out, 'ui.js'), shimSource('ui', ui).replace('window.Modulo.vendor.ui', 'window.Modulo.ui'));
    console.log(`ui.js: ${ui.length} exports from resources/js/plugin-ui.ts`);
}
